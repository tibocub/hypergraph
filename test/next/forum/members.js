// Core follow-ups, item 4: the reads the inspector asked for, as any app
// would use them — who is in a space and with which role (banned and removed
// people included), what was decided (who, what, when, why, and whether it
// counted), the declared types, a record's tags, the connected peers, and
// events when peers or logs change.

const test = require('brittle')
const forum = require('./forum.js')
const testing = require('../../../lib/testing.js')
const { account, threeMembers } = require('./_setup.js')
const { eventually, within } = require('../helpers.js')

test('members(): roles, you, devices; banned and removed people with their state', async (t) => {
  const { a, b, c, fa, fb, fc } = await threeMembers(t)
  const d = await account(t, 'd')
  const fd = await forum.join(d, await forum.invite(fa))
  await forum.post(fc, 'hi', '')
  await forum.post(fd, 'hi', '')
  await forum.giveRole(fa, b.identity.publicKey, 'moderator')
  t.ok(await eventually(async () => (await fa.inspect()).logs.filter((l) => !l.refused).length >= 4, 10000), 'a holds everyone\'s log')
  await forum.ban(fa, c.identity.publicKey, { reason: 'spam' })
  await forum.removeMember(fa, d.identity.publicKey)

  const list = await eventually(async () => {
    const m = await forum.people(fb)
    const banned = m.find((x) => x.identity === c.identity.publicKey)
    const removed = m.find((x) => x.identity === d.identity.publicKey)
    return banned && banned.banned && removed && removed.removed ? m : null
  }, 10000)
  t.ok(list, 'b lists the banned and the removed')
  const of = (who) => list.find((x) => x.identity === who.identity.publicKey)
  t.alike(list.slice(0, 2).map((m) => m.identity), [a, b].map((x) => x.identity.publicKey), 'highest role first')
  t.alike(list.slice(2).map((m) => m.identity).sort(), [c, d].map((x) => x.identity.publicKey).sort(), 'then the others')
  t.is(of(a).role, 'owner')
  t.is(of(b).role, 'moderator')
  t.is(of(b).you, true, 'this member')
  t.is(of(a).you, false)
  t.alike({ role: of(c).role, banned: of(c).banned, removed: of(c).removed }, { role: null, banned: true, removed: false })
  t.alike({ role: of(d).role, banned: of(d).banned, removed: of(d).removed }, { role: null, banned: false, removed: true })
  t.alike(of(c).devices.map((x) => x.device), [c.device.publicKey], 'the devices that wrote here')
  t.is(of(c).devices[0].log, testing.ownLog(fc))
  t.alike((await forum.people(fa)).map((m) => [m.identity, m.role, m.banned, m.removed]), list.map((m) => [m.identity, m.role, m.banned, m.removed]), 'the same on another member')
})

test('decisions(): who decided what, when and why, and whether it counted; newest first, paged', async (t) => {
  const { a, b, c, fa, fb } = await threeMembers(t)
  await forum.giveRole(fa, b.identity.publicKey, 'moderator')
  const p = await forum.post(fa, 'post', '')
  t.ok(await eventually(async () => (await fb.get(p.id)).record, 10000))
  await eventually(async () => { try { await forum.hide(fb, p, 'off topic'); return true } catch { return false } }, 10000)
  t.ok(await eventually(async () => (await fa.get(p.id)).record?.hidden, 10000), 'a applied the hide')
  await forum.giveRole(fa, b.identity.publicKey, 'member')
  // b, demoted, records a ban anyway (a modified app): it doesn't count.
  await eventually(async () => (await fb.getRole(b.identity.publicKey)) === 'member', 10000)
  await testing.decide(fb, { type: 'moderate', action: 'ban', target: require('z32').decode(c.identity.publicKey), reason: 'nope', cut: [] }).catch(() => {})

  const all = await eventually(async () => {
    const items = await forum.modLog(fa)
    return items.some((x) => x.type === 'role/set' && x.role === 'member') && items.some((x) => x.action === 'hide') ? items : null
  }, 10000)
  t.ok(all, 'every decision is listed')
  const types = all.map((x) => x.type)
  t.is(types.at(-1), 'space/init', 'oldest last')
  t.ok(all.every((x, i) => i === 0 || x.seq < all[i - 1].seq), 'newest first')
  const init = all.at(-1)
  t.is(init.by, a.identity.publicKey)
  t.is(init.device, a.device.publicKey)
  t.is(init.counted, true)
  t.is(init.name, 'Hypergraph fans')
  const promoted = all.find((x) => x.type === 'role/set' && x.role === 'moderator')
  t.alike({ by: promoted.by, identity: promoted.identity, counted: promoted.counted }, { by: a.identity.publicKey, identity: b.identity.publicKey, counted: true }, 'a role given: by whom, to whom')
  t.ok(typeof promoted.at === 'number' && promoted.at > 0, 'when')
  const hidden = all.find((x) => x.type === 'moderate' && x.action === 'hide')
  t.alike({ by: hidden.by, target: hidden.target, reason: hidden.reason, counted: hidden.counted }, { by: b.identity.publicKey, target: p.id, reason: 'off topic', counted: true }, 'a moderation: what and why')
  const redeemed = all.filter((x) => x.type === 'invite/redeem')
  t.is(redeemed.length, 2)
  t.ok(redeemed.every((x) => x.role === 'member' && x.counted), 'redemptions with their role')
  t.ok(redeemed.some((x) => x.identity === c.identity.publicKey), 'and who came in')
  const late = all.find((x) => x.type === 'moderate' && x.action === 'ban')
  if (late) t.is(late.counted, false, 'a demoted moderator\'s ban is listed, not counted')
  else t.pass('the demoted moderator could no longer write decisions at all')
  t.is(await fa.getRole(c.identity.publicKey), 'member', 'and c stays')

  const page1 = await fa.decisions({ limit: 3 })
  t.is(page1.items.length, 3)
  const page2 = await fa.decisions({ limit: 3, after: page1.items.at(-1) })
  t.alike(page2.items.map((x) => x.seq), all.slice(3, 6).map((x) => x.seq), 'paging never skips or repeats')
  t.alike((await fb.decisions({ limit: 100 })).items.map((x) => [x.seq, x.type, x.counted]), (await fa.decisions({ limit: 100 })).items.map((x) => [x.seq, x.type, x.counted]), 'the same list on every member')
})

test('types(), tags(), peers() and events when peers or logs change', async (t) => {
  const a = await account(t, 'a')
  const types = a.types()
  t.alike(types.comment.fields, { text: 'text', on: 'link' })
  t.alike(types.comment.links, { on: ['post', 'comment'] })
  t.is(types.vote.onePerMember, true)
  t.alike(types.page.editable, { permission: 'edit-pages' })
  t.alike(types.post.index, [['topic']])
  t.is(types.post.builtin, false)
  t.is(types['hg/tag'].builtin, true, 'hypergraph\'s own, marked')

  const fa = await forum.createForum(a, 'Fans')
  t.alike(fa.peers(), [], 'nobody connected yet')
  const peered = new Promise((resolve) => fa.on('peers', (peers) => { if (peers.length) resolve(peers) }))
  const grew = new Promise((resolve) => fa.on('logs', () => resolve(true)))
  const b = await account(t, 'b')
  const fb = await forum.join(b, await forum.invite(fa))
  const peers = await within(peered, 15000)
  t.ok(peers, 'a peers event when b connects')
  t.ok(await eventually(() => forum.online(fa).some((p) => p.identity === b.identity.publicKey && p.device === b.device.publicKey), 10000), 'peers(): b, its identity and device')
  const post = await forum.post(fb, 'Tagged', '')
  t.ok(await within(grew, 15000), 'a logs event when a log arrives or grows')
  await forum.tag(fb, post, 'rust')
  await forum.tag(fb, post, 'p2p')
  await forum.untag(fb, post, 'p2p')
  await forum.tag(fb, post, 'zig')
  t.ok(await eventually(async () => (await forum.tagsOf(fa, post)).join() === 'rust,zig', 10000), 'tags(): the record\'s tags, sorted')
  t.alike((await fa.tags(post)).items, (await fb.tags(post)).items)

  const left = new Promise((resolve) => fa.on('peers', (p) => { if (!p.length) resolve(true) }))
  await b.close()
  t.ok(await within(left, 15000), 'a peers event when b leaves')
  t.alike(fa.peers(), [])
})
